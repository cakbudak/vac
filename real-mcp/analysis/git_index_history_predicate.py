"""The git index rewrite: from a post-hoc observation to a pre-registered controller result.

The pilot's one state-conditional deviation on an official server is the rewrite of `.git/index`
by tools annotated `readOnlyHint: true`.  This script regenerates, from the receipts alone,
every number of `GIT_INDEX_HISTORY_PREDICATE.md`:

  1. post hoc, on the receipts of the reported run, the second machine and the agent runs: the
     history predicate P1 (the last index writer was `git_reset`) found by reading them;
  2. the pre-registered test of P1 on seeds 4-6 with the frozen harness (`PREDICTIONS.md` §2);
  3. the controller run (`history_predicate_run.py`, `PREDICTIONS.md` §3): seeds 7-9 of the same
     traffic generator and the paired probes of seed 10, with the verdicts of P1, the refined
     history predicate P2 and the state predicate S recorded BEFORE every call, next to what the
     frozen lexical learner did on the identical traffic (`scripted/git/seed-7..9`);
  4. the agent traffic of the controller phase: every attempt listed, and for a run with receipts
     P1 and P2 evaluated in traffic order with the learner's recorded verdicts beside them.

Every receipt's digest is checked.  Standard library only; receipts are read, never written.

    python3 real-mcp/analysis/git_index_history_predicate.py
"""
from __future__ import annotations

import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
HP = ROOT / "results_history_predicate"

READONLY = {"git_status", "git_diff_unstaged", "git_diff_staged", "git_diff", "git_log", "git_show", "git_branch"}
WT = {"git_status", "git_diff_unstaged", "git_diff"}
ATTACHED = ("grade", "verdicts_before_execution", "phase", "task_id", "step", "index_state_before")
problems: list[str] = []


def read_jsonl(p: Path) -> list[dict]:
    if not p.exists():
        return []
    return [json.loads(l) for l in p.read_text().splitlines() if l.strip()]


def check_digests(rs: list[dict], where: str) -> None:
    for r in rs:
        body = {k: v for k, v in r.items() if k != "digest" and k not in ATTACHED}
        if hashlib.sha256(json.dumps(body, sort_keys=True, default=str).encode()).hexdigest() != r.get("digest"):
            problems.append(f"{where}: receipt {r.get('index')} digest mismatch")


def rewrote(r: dict) -> bool:
    fs = r["fs"]
    return any(p.endswith("/.git/index") for p in fs["modified"] + fs["created"])


def err(r: dict) -> bool:
    return bool(r["is_error"] or r.get("transport_error"))


def history_verdicts(rs: list[dict]):
    """P1 and P2 evaluated in traffic order from the receipts before each call (what a controller
    holding the same history would have decided).  Yields (receipt, {P1, P2}) for read-only calls."""
    last_writer, stale = None, False
    for r in rs:
        t = r["tool"]
        if t in READONLY:
            yield r, {"P1": "review" if (t in WT and last_writer == "git_reset") else "allow",
                      "P2": "review" if (t in WT and stale) else "allow"}
            if t in WT and not err(r):
                stale = False
        if rewrote(r):
            last_writer = t
            if t == "git_reset":
                stale = True


def confusion(pairs) -> Counter:
    c = Counter()
    for r, verdict in pairs:
        if err(r):
            c["errors"] += 1
            continue
        pred, rw = verdict == "review", rewrote(r)
        c["TP" if pred and rw else "FP" if pred else "FN" if rw else "TN"] += 1
    return c


def fmt(c: Counter) -> str:
    return f"{c['TP']} / {c['FP']} / {c['FN']} / {c['TN']}"


def main() -> int:
    L = ["# The git index rewrite: from a post-hoc observation to a pre-registered controller result", "",
         "*Generated by `real-mcp/analysis/git_index_history_predicate.py` from the receipts; every receipt digest is checked. "
         "Confusion cells are TP / FP / FN / TN over read-only calls: TP = a rewrite of `.git/index` that the predicate "
         "flagged `review` before the call, FP = `review` without a rewrite, FN = a rewrite that was `allow`ed.*", ""]

    # ---- 1. post hoc on the package's original runs ---------------------------------------------
    orig = []
    for s in (1, 2, 3):
        d = ROOT / "results2" / "git" / f"seed-{s}"
        orig.append((f"reported run, seed {s}", read_jsonl(d / "receipts_train.jsonl") + read_jsonl(d / "receipts_heldout.jsonl")))
    for s in (1, 2, 3):
        d = ROOT / "results2_second_machine" / "git" / f"seed-{s}"
        orig.append((f"second machine, seed {s}", read_jsonl(d / "receipts_train.jsonl") + read_jsonl(d / "receipts_heldout.jsonl")))
    for d in sorted((ROOT / "results2_agent" / "git").glob("*/seed-1")):
        orig.append((f"agent traffic, {d.parent.name}", read_jsonl(d / "receipts_train.jsonl") + read_jsonl(d / "receipts_agent.jsonl")))
    orig = [(n, rs) for n, rs in orig if rs]
    L += ["## 1. Post hoc: what conditions the rewrite in the reported run, the second machine and the agent runs", "",
          "Read after the runs, not predicted.  **P1**: the most recent call that wrote `.git/index` was `git_reset`, and the "
          "current tool stats the working tree (`git_status`, `git_diff_unstaged`, `git_diff`).", "",
          "| Run | Read-only calls | Rewrites by read-only tools | P1 (TP / FP / FN / TN) | 2-junta verdict on the rewrites it saw |", "|---|---:|---:|---|---|"]
    tot1, ro1, rw1 = Counter(), 0, 0
    sequences = []
    for name, rs in orig:
        check_digests(rs, name)
        pairs = [(r, v["P1"]) for r, v in history_verdicts(rs)]
        c = confusion(pairs); tot1 += c
        ro = len(pairs); rw = sum(rewrote(r) for r, _ in pairs); ro1 += ro; rw1 += rw
        verdicts = [r["verdicts_before_execution"].get("2-junta", "—") for r, _ in pairs if rewrote(r) and "verdicts_before_execution" in r]
        L.append(f"| {name} | {ro} | {rw} | {fmt(c)} | {', '.join(verdicts) or '(training calls only)'} |")
        for i, r in enumerate(rs):
            if r["tool"] in READONLY and rewrote(r):
                j = i - 1
                while j >= 0 and not rewrote(rs[j]):
                    j -= 1
                sequences.append((rs[j]["tool"] if j >= 0 else "—", tuple(rs[k]["tool"] for k in range(j + 1, i)), r["tool"]))
    L.append(f"| **all** | **{ro1}** | **{rw1}** | **{fmt(tot1)}** | |")
    seqc = Counter(sequences)
    L += ["", "Every rewrite followed a `git_reset` with no other index write in between: " +
          "; ".join(f"`{w}` → {' → '.join('`' + t + '`' for t in b) + ' → ' if b else ''}`{r}` ×{n}" for (w, b, r), n in sorted(seqc.items(), key=lambda x: -x[1])) + ".",
          "", "Mechanism, from the receipts' child-process lists: `git_reset` runs `git read-tree`, which writes index entries without "
          "stat data; the next `git status` or `git diff` refreshes them and rewrites the index.  `git add` and `git checkout` "
          "write stat data for the entries they touch.  The lexical 2-junta could not express any of this: its version space "
          "emptied in seeds 2 and 3 (blanket review), it blocked one safe `git_diff_unstaged` per agent run, and it allowed the "
          "rewrite by `git_status` in all four agent runs.", ""]

    # ---- 2. pre-registered test of P1 on seeds 4-6 -----------------------------------------------
    L += ["## 2. Pre-registered test of P1: seeds 4–6 with the frozen harness", "",
          "Predicted before the run (`PREDICTIONS.md` §2): every rewrite by a read-only tool has P1 true, and every worktree-statting "
          "call with P1 true rewrites.  Frozen harness, same revision digest as the reported run, same contract.", "",
          "| Seed | Read-only calls | Rewrites | P1 (TP / FP / FN / TN) | 2-junta: hypotheses left, held-out safe reviewed | Where P1 failed |", "|---|---:|---:|---|---|---|"]
    tot2 = Counter()
    for s in (4, 5, 6):
        d = HP / "scripted" / "git" / f"seed-{s}"
        rs = read_jsonl(d / "receipts_train.jsonl") + read_jsonl(d / "receipts_heldout.jsonl")
        if not rs:
            L.append(f"| {s} | (missing) | | | | |"); continue
        check_digests(rs, f"scripted seed {s}")
        sm = json.loads((d / "summary.json").read_text())
        pairs = [(r, v["P1"]) for r, v in history_verdicts(rs)]
        c = confusion(pairs); tot2 += c
        fails = []
        for i, r in enumerate(rs):
            if r["tool"] in READONLY and rewrote(r):
                j = i - 1
                while j >= 0 and not rewrote(rs[j]):
                    j -= 1
                if rs[j]["tool"] != "git_reset":
                    k = i - 1
                    while k >= 0 and rs[k]["tool"] != "git_reset":
                        k -= 1
                    fails.append("`" + "` → `".join(rs[m]["tool"] for m in range(k, i + 1)) + "`")
        hl = sm["train"]["hypotheses_remaining"].get("2-junta"); t = sm["heldout"]["tallies"]["2-junta"]
        L.append(f"| {s} | {len(pairs)} | {sum(rewrote(r) for r, _ in pairs)} | {fmt(c)} | {hl}, {t['safe_reviewed']} of {t['safe_reviewed'] + t['safe_allowed'] + t['safe_blocked']} | {'; '.join(fails) or '—'} |")
    L.append(f"| **4–6** | | | **{fmt(tot2)}** | | |")
    L += ["", f"P1 held in {tot2['TP']} of {tot2['TP'] + tot2['FN']} rewrites and failed once: after `git_reset`, two `git_add` calls and a "
          "`git_commit`, `git_status` still rewrote the index.  `git add <file>` writes the index but refreshes only the entries it "
          "adds; the entries `git read-tree` left without stat data stay stale.  The refutation is the one the pre-registration "
          "named (\"another writer leaves stale entries\").  The prediction was amended before the next run (`PREDICTIONS.md` §3): "
          "**P2** — stale since the last `git_reset` until a worktree-statting read-only call, not cleared by `git_add`, `git_commit` "
          "or `git_create_branch`, `git_checkout` undecided — and a **state predicate S** that reads `.git/index` before the call "
          "and flags entries with zeroed stat data or a smudged size.", ""]

    # ---- 3. controller run: verdicts before execution ----------------------------------------------
    L += ["## 3. Controller run: verdicts recorded before execution (seeds 7–9 scripted, seed 10 paired probes)", "",
          "`history_predicate_run.py` drives the frozen harness and records P1, P2 and S before every read-only call.  The frozen "
          "lexical learner was run on the identical traffic of seeds 7–9 (`scripted/git/seed-7..9`) for comparison.", "",
          "| Seed | Read-only calls | Rewrites | P1 | P2 | S | 2-junta on the same traffic: hypotheses left, safe reviewed, deviations allowed |",
          "|---|---:|---:|---|---|---|---|"]
    tot3 = {"P1": Counter(), "P2": Counter(), "S": Counter()}
    ro3 = rw3 = 0
    paired_rows = None
    p2_fp, p1_fn, learner_notes = [], [], []

    def since_reset(rs: list[dict], i: int) -> str:
        """The call sequence from the last `git_reset` to call i, consecutive repeats compressed."""
        k = i - 1
        while k >= 0 and rs[k]["tool"] != "git_reset":
            k -= 1
        out: list[list] = []
        for m in range(max(k, 0), i + 1):
            if out and out[-1][0] == rs[m]["tool"]:
                out[-1][1] += 1
            else:
                out.append([rs[m]["tool"], 1])
        return " → ".join(f"`{t}`" + (f" ×{n}" if n > 1 else "") for t, n in out)

    for s in (7, 8, 9, 10):
        d = HP / "controller" / "git" / f"seed-{s}"
        rs = read_jsonl(d / "receipts.jsonl")
        if not rs:
            L.append(f"| {s} | (missing) | | | | | |"); continue
        check_digests(rs, f"controller seed {s}")
        sm = json.loads((d / "summary.json").read_text())
        ro = [r for r in rs if r["tool"] in READONLY]
        rw = sum(rewrote(r) for r in ro); ro3 += len(ro); rw3 += rw
        cs = {}
        for key, name in (("P1", "P1_last_writer_reset"), ("P2", "P2_stale_since_reset"), ("S", "S_index_state")):
            cs[key] = confusion([(r, r["verdicts_before_execution"].get(name, "allow")) for r in ro]); tot3[key] += cs[key]
        for i, r in enumerate(rs):
            if r["tool"] in READONLY and not err(r):
                v = r["verdicts_before_execution"]
                if v.get("P2_stale_since_reset") == "review" and not rewrote(r):
                    p2_fp.append(since_reset(rs, i))
                if v.get("P1_last_writer_reset") == "allow" and rewrote(r):
                    p1_fn.append(since_reset(rs, i))
        if sm.get("mode") == "paired":
            paired_rows = sm["paired"]; learner = "— (no learner in the paired run)"
        else:
            ds = HP / "scripted" / "git" / f"seed-{s}" / "summary.json"
            if ds.exists():
                lsm = json.loads(ds.read_text()); t = lsm["heldout"]["tallies"]["2-junta"]
                hl = lsm["train"]["hypotheses_remaining"].get("2-junta")
                safe_n = t["safe_reviewed"] + t["safe_allowed"] + t["safe_blocked"]
                dev_n = t["dev_allowed"] + t["dev_reviewed"] + t["dev_blocked"]
                learner = f"{hl}, {t['safe_reviewed']} of {safe_n}, {t['dev_allowed']} of {dev_n}"
                learner_notes.append(
                    f"seed {s}: " + ("version space empty, every held-out call reviewed" if hl == 0 else
                                     f"{hl} hypotheses left, {t['safe_reviewed']} of {safe_n} safe held-out calls reviewed") +
                    (f", the {dev_n} held-out rewrite{'s' if dev_n != 1 else ''} " +
                     ("allowed" if t["dev_allowed"] == dev_n else "reviewed" if t["dev_reviewed"] == dev_n else "blocked" if t["dev_blocked"] == dev_n else
                      f"{t['dev_allowed']} allowed, {t['dev_reviewed']} reviewed, {t['dev_blocked']} blocked") if dev_n else ", no rewrite in the held-out phase"))
            else:
                learner = "(not run)"
        L.append(f"| {s}{' (paired)' if sm.get('mode') == 'paired' else ''} | {len(ro)} | {rw} | {fmt(cs['P1'])} | {fmt(cs['P2'])} | {fmt(cs['S'])} | {learner} |")
    L.append(f"| **7–10** | **{ro3}** | **{rw3}** | **{fmt(tot3['P1'])}** | **{fmt(tot3['P2'])}** | **{fmt(tot3['S'])}** | |")
    s_ok = tot3["S"]["FP"] == 0 and tot3["S"]["FN"] == 0
    L += ["", (f"**S decided every one of the {ro3} read-only calls correctly with its verdict recorded before the call: {tot3['S']['TP']} rewrites "
               f"flagged, {tot3['S']['FP']} classification false positives, {tot3['S']['FN']} missed rewrites.**" if s_ok else
               f"**S: {tot3['S']['TP']} rewrites flagged, {tot3['S']['FP']} classification false positives, {tot3['S']['FN']} missed rewrites over {ro3} read-only calls.**") +
          f"  P2 flagged {tot3['P2']['TP']} of {tot3['P2']['TP'] + tot3['P2']['FN']} rewrites and raised {tot3['P2']['FP']} false review(s)" +
          (": " + "; ".join(p2_fp) + " — `git_checkout` does refresh the stale entries, the question the paired probes were to decide" if p2_fp else "") +
          f".  P1 missed {tot3['P1']['FN']} rewrite(s)" + (": " + "; ".join(p1_fn) if p1_fn else "") + ".", "",
          "The frozen 2-junta on the identical traffic (`scripted/git/seed-7..9`): " + "; ".join(learner_notes) + ".", ""]
    L += [f"Operational cost: S issues review on {tot3['S']['TP'] + tot3['S']['FP']} of {ro3} legitimate read-only calls; a correct predicted rewrite is still a review of a legitimate operation.", ""]
    if paired_rows:
        L += ["### Paired probes (seed 10), in the order of `PREDICTIONS.md` §3", "",
              "| Case | Call | Index rewritten | P1 | P2 | S | Index before the call |", "|---|---|---|---|---|---|---|"]
        for p in paired_rows:
            v = p["verdicts"]; st = p["index_state_before"] or {}
            state = "" if not st else f"{st.get('reason')} ({st.get('zero_stat')} zeroed, {st.get('smudged')} smudged, {st.get('racy')} racy of {st.get('entries')})"
            L.append(f"| {p['case']} | `{p['tool']}` | {'**yes**' if p['index_rewritten'] else 'no'} | {v.get('P1_last_writer_reset', '—')} | {v.get('P2_stale_since_reset', '—')} | {v.get('S_index_state', '—')} | {state} |")
        L += ["", "Every prediction of §3 held: `git_reset → git_status` rewrites, a second `git_status` does not, `git_add → git_status` does "
              "not, `git_reset → git_add → git_status` **does** (P2 right, P1 wrong), `git_reset → git_commit → git_status` does, "
              "`git_diff_staged`, `git_log`, `git_show` and `git_branch` after a reset do not rewrite and the `git_status` after them does.  "
              "The two open questions were answered: `git_checkout` refreshes the stale entries (no rewrite after `git_reset → git_checkout`), "
              "and `git_diff` is a refresher (it rewrites after a reset, and the `git_status` after it does not).", ""]

    # ---- 4. agent run of the controller phase --------------------------------------------------------
    agent_dirs = sorted((HP / "agent" / "git").glob("*/seed-*")) if (HP / "agent" / "git").exists() else []
    L += ["## 4. Agent traffic in the controller phase", "",
          "Every attempt is listed (`PREDICTIONS.md` §3).  For a run with receipts, P1 and P2 are evaluated in traffic order "
          "(training probes, then the agent's calls) and the frozen 2-junta's recorded verdicts stand beside them.", "",
          "| Run | Model (provider-reported) | Agent calls | Read-only calls | Rewrites | P1 | P2 | 2-junta on the rewrites | 2-junta: safe reviewed, deviations allowed |",
          "|---|---|---:|---:|---:|---|---|---|---|"]
    agent_notes = []
    attempt_only = []
    for d in agent_dirs:
        man = json.loads((d / "manifest.json").read_text()) if (d / "manifest.json").exists() else {}
        rs = read_jsonl(d / "receipts_train.jsonl") + read_jsonl(d / "receipts_agent.jsonl")
        if not rs or not (d / "summary.json").exists():
            L.append(f"| {d.parent.name} | {man.get('model', '?')} | attempt only — manifest written, no receipt | | | | | | |")
            attempt_only.append(man.get("model", d.parent.name))
            continue
        check_digests(rs, f"agent {d.parent.name}")
        sm = json.loads((d / "summary.json").read_text())
        pairs = list(history_verdicts(rs))
        c1 = confusion([(r, v["P1"]) for r, v in pairs]); c2 = confusion([(r, v["P2"]) for r, v in pairs])
        t = sm["agent"]["tallies"]["2-junta"]
        verdicts = [r["verdicts_before_execution"].get("2-junta", "—") for r, _ in pairs if rewrote(r) and "verdicts_before_execution" in r]
        safe_n = t["safe_reviewed"] + t["safe_allowed"] + t["safe_blocked"]; dev_n = t["dev_allowed"] + t["dev_reviewed"] + t["dev_blocked"]
        L.append(f"| {d.parent.name} | {man.get('model')} | {sm['agent']['calls']} | {len(pairs)} | {sum(rewrote(r) for r, _ in pairs)} | {fmt(c1)} | {fmt(c2)} | "
                 f"{', '.join(verdicts) or '(no rewrite while the agent worked)'} | {t['safe_reviewed']} of {safe_n}, {t['dev_allowed']} of {dev_n} |")
        seqs = [since_reset(rs, i) for i, r in enumerate(rs) if r["tool"] in READONLY and rewrote(r)]
        agent_notes.append(f"{d.parent.name}: {len(pairs)} read-only calls, {len(seqs)} rewrite{'s' if len(seqs) != 1 else ''}" +
                           (" (" + "; ".join(seqs) + ")" if seqs else "") +
                           f"; P1 {fmt(c1)}, P2 {fmt(c2)}; {sm['agent'].get('tasks_finished', '?')} of {sm.get('tasks', '?')} tasks finished, "
                           f"{sm['agent'].get('tool_errors', '?')} tool errors")
    if agent_notes:
        L += ["", " ".join(agent_notes) + "."]
    if attempt_only:
        L += ["", "Both attempts (" + ", ".join(attempt_only) + ") timed out on every tool-use request at the provider before "
              "any tool call; the agent-traffic evidence for the history predicate is the four git agent runs of §1, where P1 "
              "holds on 8 of 8 rewrites over 81 read-only calls."]
    L.append("")

    # ---- 5. reading ----------------------------------------------------------------------------------
    L += ["## 5. Reading", "",
          "With verdicts recorded before execution, the pilot's one state-conditional deviation on an official server is decided "
          "from state: a controller that reads the one file the tool is about to touch decides every call, where the lexical "
          "learner either emptied its version space (blanket review) or allowed the rewrite.  Of the 12 rewrites of the controller "
          "run, 4 occurred in scripted traffic (seeds 7–9, 66 read-only calls) and 8 in the paired probes (seed 10, 19 calls).  "
          "P1 was written from the receipts of the reported run, P2 and S from those of seeds 4–6, and each was scored only on "
          "runs made after it was fixed: the first history predicate was refuted once, the refutation named the mechanism, and "
          "the paired probes answered the two questions declared open.  S, frozen, decides ten further seeds and runs as the "
          "policy of the enforcing proxy in `GUARDED_RUN.md`.", ""]
    out = HERE / "GIT_INDEX_HISTORY_PREDICATE.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))
    if problems:
        print("PROBLEMS:", *problems, sep="\n  ")
        return 1
    print("written", out, "- every receipt digest verified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
