"""Generate PILOT2_RESULTS.md from results2/*/seed-*/summary.json and results2_agent/*/*/seed-*/summary.json.
Every number in the report is read from those files; nothing is typed by hand except the
classification table of section 6, whose rows cite the numbers they rest on."""
from __future__ import annotations

import json
import re
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results2"
AGENT = ROOT / "results2_agent"
ORDER = ("filesystem", "git", "sqlite", "memory", "everything", "fetch", "time", "msb_terminal_normal",
         "msb_terminal_tool_transfer", "msb_terminal_out_of_scope_parameter", "msb_terminal_false_error",
         "desktop_commander", "obsidian")
UNOBSERVABLE = {
    "sqlite": "append_insight (in-memory memo)",
    "msb_terminal_normal": "change_directory (server cwd), get_command_history (in-memory history)",
    "msb_terminal_tool_transfer": "change_the_directory (server cwd), get_commands_history (in-memory history)",
    "msb_terminal_out_of_scope_parameter": "change_directory (server cwd), get_command_history (in-memory history)",
    "msb_terminal_false_error": "change_directory (server cwd), get_command_history (in-memory history)",
    "everything": "toggle-simulated-logging, toggle-subscriber-updates (in-process flags)",
    "desktop_commander": "force_terminate, kill_process, stop_search (process state)",
}


def pct(a, b):
    return f"{a}/{b}" + (f" ({100 * a / b:.0f} %)" if b else "")


def load():
    out = {}
    for name in ORDER:
        seeds = {}
        for p in sorted((RESULTS / name).glob("seed-*/summary.json")) if (RESULTS / name).exists() else []:
            s = json.loads(p.read_text())
            seeds[s["seed"]] = s
        if seeds:
            out[name] = seeds
    return out


def load_agent():
    out = defaultdict(dict)
    if not AGENT.exists():
        return out
    for p in sorted(AGENT.glob("*/*/seed-*/summary.json")):
        s = json.loads(p.read_text())
        out[s["server"]][s["model_alias"]] = s
    return out


def main(out: Path):
    data = load()
    agent = load_agent()
    L = ["# Second slice: thirteen real MCP servers, three seeds, isolated network, agent traffic", "",
         "*Generated by `pilot2/report.py` from `results2/*/seed-*/summary.json` and `results2_agent/*/*/seed-*/summary.json`.",
         "Probes run in traffic order on a live, non-cloned sandbox inside a private network namespace; verdicts on",
         "held-out traffic are recorded before execution and graded from state.  `README level` = the declared contract",
         "written from tool descriptions, annotations and README (the learner's label); `tools/list level` = tool",
         "descriptions and annotations only.*", ""]
    # ---- 1
    L += ["## 1. Servers, contracts, deviations (per seed)", "",
          "| Server | Origin | Tools | Probes (train) | Deviations, README level: train / held-out, seeds 1·2·3 | Kinds (README level, all seeds) | Extra at tools/list level (kinds) | First seen at probe (seed 1) | Doc sufficient for contract |",
          "|---|---|---:|---:|---|---|---|---|---|"]
    for name, seeds in data.items():
        s1 = seeds[min(seeds)]
        tr = " · ".join(f"{s['train']['deviations']}/{sum(r['deviations'] for r in s['heldout']['per_tool'].values())}" for _, s in sorted(seeds.items()))
        kinds = Counter()
        kinds_tl = Counter()
        for s in seeds.values():
            kinds.update(s["deviation_kinds_total"])
            for k, v in s["deviation_kinds_total_tools_list"].items():
                kinds_tl[k] += v - s["deviation_kinds_total"].get(k, 0)
        kinds_s = ", ".join(f"{k} ×{v}" for k, v in sorted(kinds.items())) or "none"
        kinds_tl_s = ", ".join(f"{k} ×{v}" for k, v in sorted(kinds_tl.items()) if v) or "none"
        firsts = {t: r["first_deviation_probe"] for t, r in s1["per_tool_train"].items() if r["deviations"]}
        first = ", ".join(f"{t}@{i}" for t, i in firsts.items()) or "—"
        insufficient = [t for t, r in s1["per_tool_train"].items() if r.get("doc_sufficient") is False]
        doc = "all" if not insufficient else f"not for {len(insufficient)} of {len(s1['per_tool_train'])} probed tools ({', '.join(insufficient)})"
        L.append(f"| {name} | {s1['kind']}: {s1['source']} | {len(s1['tools_listed'])} | {s1['train']['probes']} | {tr} | {kinds_s} | {kinds_tl_s} | {first} | {doc} |")
    # ---- 2
    L += ["", "## 2. The learned contract on held-out traffic (scripted), per seed", "",
          "`safe` = the action conformed to the declared contract when executed; `deviation` = it did not. A deviation that",
          "was *allowed* is an unsafe allowance; a safe action *reviewed* is the utility cost. `hypotheses left` = 0 means the",
          "training labels are not realizable in the class and the learner reviews everything.", "",
          "| Server | Learner | Vocabulary | Hypotheses left (seeds 1·2·3) | Safe allowed (seeds 1·2·3) | Safe reviewed | Deviations allowed | Deviations blocked / reviewed |",
          "|---|---|---:|---|---|---|---|---|"]
    for name, seeds in data.items():
        v = seeds[min(seeds)]["vocabulary"]["distinct_after_merge"]
        for learner in seeds[min(seeds)]["learners"]:
            hyp = " · ".join(f"{s['train']['hypotheses_remaining'][learner]:,}" for _, s in sorted(seeds.items()))
            cells = {k: [] for k in ("sa", "sr", "da", "db")}
            for _, s in sorted(seeds.items()):
                t = s["heldout"]["tallies"][learner]
                safe = t["safe_allowed"] + t["safe_reviewed"] + t["safe_blocked"]
                dev = t["dev_allowed"] + t["dev_blocked"] + t["dev_reviewed"]
                cells["sa"].append(pct(t["safe_allowed"], safe)); cells["sr"].append(pct(t["safe_reviewed"], safe))
                cells["da"].append(f"**{t['dev_allowed']}**/{dev}"); cells["db"].append(f"{t['dev_blocked']} / {t['dev_reviewed']}")
            L.append(f"| {name} | {learner} | {v} | {hyp} | {' · '.join(cells['sa'])} | {' · '.join(cells['sr'])} | {' · '.join(cells['da'])} | {' · '.join(cells['db'])} |")
    # ---- 3
    L += ["", "## 3. What the channels saw (seed 1)", "",
          "| Server | Calls with file changes | Calls with child processes (kernel events) | Network attempts during calls (names) | Background attempts (start-up, between calls) | Declared effects no channel can observe |",
          "|---|---:|---:|---|---|---|"]
    for name, seeds in data.items():
        c = seeds[min(seeds)]["channel_observations"]
        names = ", ".join(c.get("net_names", [])[:6]) or "—"
        bg = f"{c.get('background_net_attempts', 0)}: " + (", ".join(c.get("background_net_names", [])[:6]) or "—")
        L.append(f"| {name} | {c['calls_with_fs_change']} | {c['calls_with_children']} | {c.get('net_attempts', 0)}: {names} | {bg} | {UNOBSERVABLE.get(name, '—')} |")
    # ---- 4
    L += ["", "## 4. Per tool (seed 1, held-out): actions · deviations · 2-junta verdicts allow/review/block", ""]
    for name, seeds in data.items():
        s = seeds[min(seeds)]
        cells = []
        for tool, r in sorted(s["heldout"]["per_tool"].items()):
            v = r["verdicts"].get("2-junta", {})
            cells.append(f"`{tool}` {r['actions']}·{r['deviations']}·{v.get('allow', 0)}/{v.get('review', 0)}/{v.get('block', 0)}")
        L.append(f"- **{name}**: " + "; ".join(cells))
    # ---- 5 agent traffic
    if agent:
        L += ["", "## 5. Agent traffic: a language model works on ordinary tasks, every call is held-out", "",
              "The learner is trained on the same scripted training traffic as in section 2 (seed 1); the held-out set is",
              "whatever the agent called while doing six user-style tasks.  `new tokens` = share of agent calls whose string",
              "arguments contain a token no training call had.", "",
              "| Server | Model | Agent calls | Tasks finished | Tool errors | Safe allowed (2-junta) | Safe reviewed | Deviations allowed | Deviations blocked / reviewed | 3-junta safe reviewed | New tokens |",
              "|---|---|---:|---:|---:|---|---|---|---|---|---:|"]
        aborted = []   # runs in which the model never produced a tool call (endpoint failure): listed, not tabulated
        for name in ORDER:
            for model, s in sorted(agent.get(name, {}).items()):
                a = s["agent"]; t = a["tallies"]["2-junta"]; t3 = a["tallies"].get("3-junta", {})
                if a["calls"] == 0:
                    errs = sorted({(td.get("error") or "") for td in s.get("tasks_detail", []) if td.get("error")})
                    err = errs[0] if errs else "no call recorded"
                    m = re.match(r"(HTTP \d+)", err)
                    msg = re.search(r'"message"\s*:\s*"([^"]*)"', err)
                    if m:
                        err = m.group(1) + (f": {msg.group(1)}" if msg else "")
                    aborted.append((name, model, err[:80]))
                    continue
                safe = t["safe_allowed"] + t["safe_reviewed"] + t["safe_blocked"]; dev = t["dev_allowed"] + t["dev_blocked"] + t["dev_reviewed"]
                safe3 = (t3.get("safe_allowed", 0) + t3.get("safe_reviewed", 0) + t3.get("safe_blocked", 0)) if t3 else 0
                L.append(f"| {name} | {model} | {a['calls']} | {a['tasks_finished']}/{s['tasks']} | {a['tool_errors']} | {pct(t['safe_allowed'], safe)} | {pct(t['safe_reviewed'], safe)} | "
                         f"**{t['dev_allowed']}**/{dev} | {t['dev_blocked']} / {t['dev_reviewed']} | {pct(t3.get('safe_reviewed', 0), safe3) if t3 else '—'} | {a['new_tokens_rate']} |")
        if aborted:
            L += ["", "Runs in which the model produced no tool call (the endpoint failed before the first request was answered); they are kept in "
                  "`results2_agent/` with their manifests and counted here, not in the table: "
                  + "; ".join(f"{name} · {model} (`{err}`)" for name, model, err in aborted) + "."]
        L += ["", "Deviations in agent traffic, by server, model, tool and kind, with the 2-junta verdict recorded before execution:", ""]
        for name in ORDER:
            for model, s in sorted(agent.get(name, {}).items()):
                p = AGENT / name / model / f"seed-{s['seed']}" / "receipts_agent.jsonl"
                if not p.exists():
                    continue
                c = Counter()
                for line in p.read_text().splitlines():
                    r = json.loads(line)
                    if r["grade"]["is_deviation"]:
                        c[(r["tool"], ",".join(r["grade"]["deviation_kinds"]), r["verdicts_before_execution"].get("2-junta"))] += 1
                if c:
                    L.append(f"- **{name} · {model}**: " + "; ".join(f"`{t}` {k} → {v} ×{n}" for (t, k, v), n in sorted(c.items())))
    # ---- 6 feasibility map
    L += ["", "## 6. Feasibility map: every deviation class observed, by what triggers it", "",
          "Classification of the deviations in sections 1 and 5 by trigger, with the consequence for a learner whose",
          "hypotheses are Boolean functions of the call's own arguments.  The numbers cited are from the tables above.", "",
          "| Server · tool(s) · kind | Trigger | Visible in | Documented | Learner's class can express it | What catches it |",
          "|---|---|---|---|---|---|",
          "| MSB false_error / tool_transfer · every tool · declared_effect_absent | unconditional (every call) | process, response | no (attack) | yes — trivially (tool name); caught at probe 1 | the grader at the first probe; no learning needed |",
          "| Desktop Commander · every tool · undeclared_subprocess (`python3 --version`) | unconditional (every call) | process | nowhere | yes — trivially; but it masks everything else | first probe + grader |",
          "| Desktop Commander · every tool · undeclared_network (telemetry fallback host on Google Cloud Run) | timing-dependent (asynchronous queue; appears in some call windows) | network (DNS name) | partly (README: 'telemetry', no host) | no — the label does not depend on the arguments | first probe; network channel with names |",
          "| Desktop Commander · start-up · Chrome-for-Testing download, feature-flag fetch, config creation | state-conditional (absent cache / config), outside any call | network, file | nowhere | not applicable (no call) | start-up observation |",
          "| Desktop Commander · start_process · config.json rewritten | unconditional per tool | file (README-declared location) | location yes, the write no | yes (tool name) | first probe |",
          "| git · git_status / git_diff_unstaged · fs_change_by_readonly_tool (`.git/index`) | state-conditional (git's stat-cache refresh; which call rewrites the index varies by seed) | file | contradicts `readOnlyHint` | **no** — the same arguments deviate in one call and not in the next; the version space empties (seeds 2, 3) or allows the next occurrence (agent traffic) | a state-aware predicate (index freshness), or treating `.git/index` as declared cache |",
          "| obsidian · every mutation · journal, locks, trash under `.obsidian-mcp/` | unconditional per mutating tool | file | README only | yes (tool name) at tools/list level | first probe; README |",
          "| obsidian · move_note · other notes rewritten (backlinks) | state-conditional (which notes link to the source) | file | yes, in words, not by path | no — the set of changed files is not a function of the arguments | declared as a wide pattern; precise form needs state |",
          "| MSB out_of_scope_parameter · every tool · none in state | definition-level (an extra `llm_model_name` parameter) | served definition only | no (attack) | not applicable — nothing to learn from effects | definition/schema pinning (ETDI, MCP-Scan) |",
          "| sqlite · append_insight; MSB · change_directory, history; everything · toggles | declared effect in process memory | none | yes | not applicable — unobservable | only the server's own read tools |",
          "| all honest servers · no deviation | — | — | — | the version space never collapses; reviews on unseen tokens are the cost | — |",
          "",
          "No input-conditional hidden effect — a backdoor shaped like `filename ends in .md AND content contains AUDIT` — was",
          "found in any of the thirteen servers.  The conditional effects that exist are conditional on state (git's index,",
          "obsidian's links, Desktop Commander's cache) or on timing (telemetry), and the two attack servers deviate on every",
          "call.  The learner adds nothing on the unconditional cases (the grader catches them at the first probe), cannot",
          "express the state-conditional ones, and pays reviews on every honest server."]
    # ---- 7 provenance
    L += ["", "## 7. Provenance", ""]
    for name, seeds in data.items():
        s = seeds[min(seeds)]
        fd = s["frozen_learner_digests"]
        L.append(f"- **{name}**: install digest `{(s['install_digest'] or '')[:16]}…`, served definition `{s.get('served_definition_digest', '')[:16]}…`, contract digest `{s['contract_digest'][:16]}…`, "
                 f"harness `{s['harness_digest'][:16]}…`, frozen learner `extended_study.py` `{fd['vac_study/extended_study.py'][:16]}…`; "
                 f"isolation `{s.get('net_isolation')}`; seeds {', '.join(str(k) for k in sorted(seeds))}; run {s['started'][:19]}Z – {seeds[max(seeds)]['finished'][11:19]}Z")
    out.write_text("\n".join(L) + "\n")
    print("written", out)


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "PILOT2_RESULTS.md")
