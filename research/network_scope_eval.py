"""Call-scoped network declarations applied to the recorded Desktop Commander receipts.

`runtime/network_scope.py` grants `read_file` network access only to the host of the call's own
URL (`isUrl: true`) and keeps README-documented background hosts as a separate class.  This script
applies it to every recorded call of the reported run and of the second machine and writes
NETWORK_SCOPE_RESULTS.md.  Receipt digests are checked; receipts are read, never written.

    python3 research/network_scope_eval.py
"""
from __future__ import annotations

import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from runtime.network_scope import classify_attempts  # noqa: E402

RUNS = {"reported run": ROOT / "real-mcp/results2/desktop_commander",
        "second machine": ROOT / "real-mcp/results2_second_machine/desktop_commander"}
README_HOSTS = ("desktopcommander.app", "*.desktopcommander.app")   # contracts/desktop_commander.yaml, README level
ATTACHED = ("grade", "verdicts_before_execution", "phase", "task_id", "step")
DEST = ROOT / "research/NETWORK_SCOPE_RESULTS.md"


def receipts(d: Path):
    for f in sorted(d.glob("seed-*/receipts_*.jsonl")):
        for line in f.read_text().splitlines():
            if not line.strip():
                continue
            r = json.loads(line)
            body = {k: v for k, v in r.items() if k != "digest" and k not in ATTACHED}
            if hashlib.sha256(json.dumps(body, sort_keys=True, default=str).encode()).hexdigest() != r["digest"]:
                raise SystemExit(f"{f}: receipt {r.get('index')} digest mismatch")
            yield r


def evaluate(d: Path) -> Counter:
    c = Counter()
    for r in receipts(d):
        names = sorted({a.get("qname") or a.get("host") or "" for a in r["net_attempts"]} - {""})
        if not names:
            continue
        c["calls with DNS attempts"] += 1
        findings = classify_attempts(tool=r["tool"], arguments=r["args"], names=names, readme_hosts=README_HOSTS)
        statuses = {f.status for f in findings}
        fallback = [f for f in findings if f.host.endswith(".run.app")]
        graded = any(k in ("undeclared_network", "network_outside_scope") for k in r["grade"]["deviation_kinds"])
        c["README-documented host only"] += statuses == {"readme_documented"}
        c["allowed by the call's own URL"] += "allowed_call" in statuses
        if fallback:
            c["fallback host"] += 1
            c["fallback host, flagged call-scoped"] += all(f.status == "undeclared" for f in fallback)
            c["fallback host, flagged by the pilot grade"] += graded
            c["fallback host on local read_file"] += r["tool"] == "read_file" and r["args"].get("isUrl") is not True
    return c


def main() -> None:
    results = {name: evaluate(d) for name, d in RUNS.items()}
    rows = ["calls with DNS attempts", "README-documented host only", "allowed by the call's own URL", "fallback host",
            "fallback host, flagged by the pilot grade", "fallback host, flagged call-scoped", "fallback host on local read_file"]
    L = ["# Call-scoped network declarations on the Desktop Commander receipts", "",
         "*Generated by `research/network_scope_eval.py` from the recorded receipts (3 seeds per run); every receipt "
         "digest is checked.*", "",
         "`runtime/network_scope.py` grants `read_file` network access only to the host of the call's own URL "
         "(`isUrl: true`) and treats the README's telemetry domain as a documented background host.", "",
         "| Calls | " + " | ".join(results) + " |", "|---|" + "---:|" * len(results)]
    for row in rows:
        L.append(f"| {row} | " + " | ".join(str(results[n][row]) for n in results) + " |")
    rep = results["reported run"]
    L += ["", f"Every call that reached the fallback host is flagged under the call-scoped declaration "
          f"({rep['fallback host, flagged call-scoped']} of {rep['fallback host']} in the reported run), including the "
          f"{rep['fallback host on local read_file']} local `read_file` calls that the tool-wide declaration "
          "of URL access excused.", ""]
    DEST.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
