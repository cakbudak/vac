"""State-feature selection on the recorded git controller receipts.

A deterministic depth-2 decision tree selects among the pre-call index-state counters and
the tool names.  It is fitted on controller seeds 7-8 and scored on seeds 9-10; the same tree,
frozen, is evaluated on ten new seeds by `real-mcp/analysis/guarded_run.py`.
Run: python3 research/state_eval.py
"""
from __future__ import annotations
import json
import math
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "real-mcp/results_history_predicate/controller/git"
DEST = ROOT / "research/STATE_FEATURE_RESULTS.md"
READONLY = {"git_status", "git_diff_unstaged", "git_diff_staged", "git_diff", "git_log", "git_show", "git_branch"}


def read(seed: int) -> list[dict]:
    p = SOURCE / f"seed-{seed}/receipts.jsonl"
    return [json.loads(s) for s in p.read_text().splitlines() if s.strip()]


def outcome(row: dict) -> bool:
    return any(str(p).endswith("/.git/index") for p in row["fs"]["modified"] + row["fs"]["created"])


def attributes(row: dict) -> dict[str, bool]:
    """Candidate Boolean features from available, manually instrumented pre-call state."""
    state = row.get("index_state_before") or {}
    facts = {f"tool:{t}": row["tool"] == t for t in sorted(READONLY)}
    for key in ("zero_stat", "smudged", "racy", "entries"):
        value = state.get(key)
        facts[f"index.{key}>0"] = isinstance(value, (int, float)) and value > 0
    return facts


def entropy(rows: list[dict]) -> float:
    if not rows:
        return 0
    n = len(rows)
    p = sum(outcome(r) for r in rows) / n
    return 0 if p in (0, 1) else -p * math.log2(p) - (1 - p) * math.log2(1 - p)


def fit(rows: list[dict], columns: tuple[str, ...], depth: int = 2):
    positives = sum(outcome(r) for r in rows)
    if depth <= 0 or positives in (0, len(rows)) or len(rows) < 2:
        return {"leaf": "review" if positives else "allow", "samples": len(rows), "positive": positives}
    total_entropy = entropy(rows)
    best = None
    for col in columns:
        left = [r for r in rows if attributes(r)[col]]
        right = [r for r in rows if not attributes(r)[col]]
        if not left or not right:
            continue
        score = total_entropy - len(left)/len(rows)*entropy(left) - len(right)/len(rows)*entropy(right)
        candidate = (score, col, left, right)
        if best is None or score > best[0] + 1e-9 or (abs(score-best[0]) <= 1e-9 and col < best[1]):
            best = candidate
    if best is None or best[0] <= 0:
        return {"leaf": "review" if positives else "allow", "samples": len(rows), "positive": positives}
    _, col, left, right = best
    remaining = tuple(c for c in columns if c != col)
    return {"feature": col, "yes": fit(left, remaining, depth-1), "no": fit(right, remaining, depth-1)}


def predict(tree: dict, row: dict) -> str:
    while "feature" in tree:
        tree = tree["yes" if attributes(row)[tree["feature"]] else "no"]
    return tree["leaf"]


def score(rows: list[dict], rule):
    c = Counter()
    for r in rows:
        pred = rule(r)
        truth = outcome(r)
        c["calls"] += 1
        c["rewrites"] += int(truth)
        c["review"] += int(pred != "allow")
        c["true_review"] += int(truth and pred != "allow")
        c["false_review"] += int(not truth and pred != "allow")
        c["unsafe_allow"] += int(truth and pred == "allow")
    return c


def main() -> None:
    train = [r for seed in (7, 8) for r in read(seed) if r["tool"] in READONLY]
    test = [r for seed in (9, 10) for r in read(seed) if r["tool"] in READONLY]
    cols = tuple(sorted(attributes(train[0])))
    tree = fit(train, cols)
    # Equal available receipts/probe observations, but baseline is intentionally simple.
    prior_by_tool = {t: any(outcome(r) for r in train if r["tool"] == t) for t in READONLY}
    baselines = {
        "Allow all": lambda r: "allow",
        "Review all": lambda r: "review",
        "Per-tool observed deviation (dynamic baseline)": lambda r: "review" if prior_by_tool[r["tool"]] else "allow",
        "Automatic tree (existing state fields)": lambda r: predict(tree, r),
        "Hand-written state predicate S": lambda r: r["verdicts_before_execution"]["S_index_state"],
    }
    results = {name: score(test, rule) for name, rule in baselines.items()}
    lines = [
        "# State-feature selection on recorded git calls",
        "",
        "*Generated by `research/state_eval.py` from `real-mcp/results_history_predicate/controller/git/`.*",
        "",
        "A deterministic depth-2 decision tree selects among the index-state counters read before each call "
        "(zeroed stat data, smudged sizes, racily clean entries, entry count) and the tool names.  It is fitted on "
        "controller seeds 7–8 and scored on seeds 9–10 (seed 10 is the paired-probe sequence).  The per-tool baseline "
        "sees the same receipts and reviews every tool that rewrote the index in training.  Every call is legitimate, "
        "so every review is a held legitimate call.",
        "",
        f"Training: {len(train)} read-only calls, {sum(outcome(r) for r in train)} index rewrites. "
        f"Evaluation: {len(test)} read-only calls, {sum(outcome(r) for r in test)} rewrites.",
        "",
        "| Comparator | Reviewed legitimate calls | Reviews on rewrites | Reviews without rewrite | Rewrites allowed |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, s in results.items():
        lines.append(f"| {name} | {s['review']}/{s['calls']} | {s['true_review']}/{s['rewrites']} | "
                     f"{s['false_review']} | {s['unsafe_allow']} |")
    lines += [
        "", "Selected tree (training data only):", "", "```json", json.dumps(tree, indent=2, sort_keys=True), "```",
        "", "The tree selects `index.smudged>0`, the condition S is written on, from two positive training calls, and "
        "adds reviews only for read-only tools that do not stat the working tree.  Frozen and evaluated on ten new "
        "seeds of scripted traffic, it flags every rewrite (`real-mcp/analysis/GUARDED_RUN.md` §1).", "",
    ]
    DEST.write_text("\n".join(lines))
    print("\n".join(lines))
    return results


if __name__ == "__main__":
    main()
