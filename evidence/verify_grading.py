"""Recompute every stored grade label from the raw receipts and the shipped contracts.

Reads every scripted and agent run, regrades each receipt with the shipped grader and
compares every label field; receipts are read, never written.  Writes GRADING_AUDIT.md.
"""
from __future__ import annotations
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PILOT = ROOT / "real-mcp" / "pilot2"
sys.path.insert(0, str(PILOT))
from contracts import load  # noqa


def context_from_summary(summary):
    if not summary.get("sandbox"):
        return None
    root = summary["sandbox"].rstrip("/")
    return {
        "root": root, "work": f"{root}/work", "home": f"{root}/home", "tmp": f"{root}/tmp",
        "db": f"{root}/work/pilot.db", "repo": f"{root}/work/repo",
        "vault": f"{root}/work/notes", "memory_file": f"{root}/work/memory.json",
    }


def context_from_rows(rows):
    for r in rows:
        for value in list(r["args"].values()) + sum((r["fs"][kind] for kind in ("created", "modified", "deleted")), []):
            if isinstance(value, str):
                match = re.search(r"^(.*/sandboxes(?:/agent-[^/]+)?/[^/]+-\d+)/", value)
                if match:
                    return context_from_summary({"sandbox": match.group(1)})
    return None


def compare(run_dir):
    summary = json.loads((run_dir / "summary.json").read_text())
    rows = []
    for name in ("receipts_setup.jsonl", "receipts_train.jsonl", "receipts_heldout.jsonl", "receipts_agent.jsonl"):
        p = run_dir / name
        if p.exists():
            rows += [json.loads(l) for l in p.read_text().splitlines() if l.strip()]
    context = context_from_summary(summary) or context_from_rows(rows)
    issues = []
    if context is None:
        return {"run": str(run_dir.relative_to(ROOT)), "calls": len(rows), "error": "missing sandbox path"}
    contract = load(summary["server"], ROOT / "real-mcp/contracts")
    counter = Counter()
    for r in rows:
        expected = contract.grade(r, context)
        observed = r["grade"]
        for field in ("is_deviation", "is_deviation_tools_list", "deviation_kinds",
                      "deviation_kinds_tools_list", "flags", "known_tool"):
            if expected.get(field) != observed.get(field):
                counter[field] += 1
                if len(issues) < 4:
                    issues.append({"index": r["index"], "tool": r["tool"], "field": field,
                                   "expected": expected.get(field), "observed": observed.get(field)})
    return {"run": str(run_dir.relative_to(ROOT)), "calls": len(rows),
            "mismatches": dict(counter), "examples": issues,
            "regraded": len(summary.get("regraded", []))}


def main():
    runs = sorted((ROOT/"real-mcp/results2").glob("*/seed-*/summary.json"))
    runs += sorted((ROOT/"real-mcp/results2_agent").glob("*/*/seed-*/summary.json"))
    results = [compare(p.parent) for p in runs]
    calls = sum(r["calls"] for r in results)
    mismatch = Counter()
    for r in results:
        mismatch.update(r.get("mismatches", {}))
    failures = [r for r in results if r.get("mismatches") or r.get("error")]
    lines = ["# Regrading audit from raw receipts", "",
             "*Generated by `evidence/verify_grading.py`.*  Every stored label recomputed from the raw "
             "receipt with the shipped grader and the shipped contracts.", "",
             f"Runs: {len(results)}; receipts: {calls}; runs with differences or missing context: {len(failures)}.",
             f"Field differences: {dict(mismatch)}.", "",
             "## Runs with differences", ""]
    if failures:
        for r in failures:
            lines.append(f"- `{r['run']}`: {r.get('error') or r.get('mismatches')}, examples {r.get('examples', [])}")
    else:
        lines.append("None against the shipped contracts.")
    lines += [""]
    report = ROOT/"evidence/GRADING_AUDIT.md"
    report.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:8]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
